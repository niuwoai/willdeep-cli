import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(new URL("../web/package.json", import.meta.url));
const { Terminal } = require("@xterm/headless");
const [path, output, cols = "100", rows = "30"] = process.argv.slice(2);
let data = await readFile(path);
const leave = data.lastIndexOf(Buffer.from("\x1b[?1049l"));
if (leave >= 0) data = data.subarray(0, leave);
const terminal = new Terminal({ cols: Number(cols), rows: Number(rows), allowProposedApi: true });
await new Promise((resolve) => terminal.write(data, resolve));
const lines = Array.from({ length: terminal.buffer.active.length }, (_, index) => (terminal.buffer.active.getLine(index)?.translateToString(true) ?? "").trimEnd());
const text = lines.join("\n");
if (output) await writeFile(output, text);
const bg = (x, y) => terminal.buffer.active.getLine(y)?.getCell(x)?.getBgColor();
const last_row_bgs = Array.from({ length: Number(cols) }, (_, x) => bg(x, Number(rows) - 1));
process.stdout.write(JSON.stringify({ text, lines, chat_bg: bg(1, 0), input_bg: bg(1, Number(rows) - 2), last_row_bgs }));
terminal.dispose();
